"""Judge Calibration — expert review, adjudication and agreement analysis."""
import os
import requests
import pandas as pd
import streamlit as st

st.set_page_config(page_title="Judge Calibration", page_icon="⚖️", layout="wide")
API_URL = os.getenv("API_BASE_URL", "https://llm-prompt-benchmark.onrender.com").rstrip("/")


def secret(name, fallback=""):
    try:
        return str(st.secrets.get(name, os.getenv(name, fallback))).strip()
    except Exception:
        return os.getenv(name, fallback).strip()


def api(method, path, **kwargs):
    headers = kwargs.pop("headers", {})
    headers["X-Review-API-Key"] = st.session_state.get("calibration_key", "")
    response = requests.request(method, f"{API_URL}{path}", headers=headers, timeout=kwargs.pop("timeout", 90), **kwargs)
    if not response.ok:
        try:
            detail = response.json().get("detail", response.text)
        except ValueError:
            detail = response.text
        raise RuntimeError(f"HTTP {response.status_code}: {detail}")
    return response.json() if response.content else {}


st.title("⚖️ Judge Calibration")
st.caption("Compare LLM judge decisions with independent expert labels, resolve disagreements and measure criterion-level reliability.")

with st.sidebar:
    st.subheader("Reviewer access")
    key = secret("REVIEW_API_KEY") or st.session_state.get("calibration_key", "")
    entered = st.text_input("Review API key", type="password", value=key)
    if entered:
        st.session_state["calibration_key"] = entered
    st.caption("The key is used for authenticated API requests only.")

if not st.session_state.get("calibration_key"):
    st.info("Enter the review API key in the sidebar to access human annotation and calibration.")
    st.stop()

tab_expert, tab_report = st.tabs(["① Expert review & adjudication", "② Reliability report"])

with tab_expert:
    st.subheader("Load an existing judge evaluation")
    st.write("Open the evaluation ID generated by Rubric Studio → Evaluate response.")
    with st.form("load_judge_evaluation"):
        evaluation_id = st.text_input("Rubric evaluation ID", value=st.session_state.get("calibration_eval_id", ""), placeholder="Paste evaluation UUID")
        load = st.form_submit_button("Load evaluation", type="primary", use_container_width=True)
    if load:
        try:
            with st.spinner("Loading evaluation and preparing its review task…"):
                payload = api("GET", f"/rubrics/evaluations/{evaluation_id.strip()}")
                task = api("POST", f"/rubrics/evaluations/{evaluation_id.strip()}/review-task")
            st.session_state["calibration_eval"] = payload
            st.session_state["calibration_eval_id"] = evaluation_id.strip()
            st.success(f"Evaluation loaded · Review task {task.get('status', 'ready')}")
        except Exception as exc:
            st.error(f"Could not load evaluation: {exc}")

    payload = st.session_state.get("calibration_eval")
    if payload:
        st.divider()
        st.subheader("Evaluation context")
        with st.container(border=True):
            st.markdown("**Original prompt**")
            st.write(payload.get("prompt_text", ""))
            st.divider()
            st.markdown("**Assistant response**")
            st.write(payload.get("response_text", ""))
        scores = payload.get("scores", [])
        if not scores:
            st.warning("This evaluation contains no criterion scores.")
        else:
            st.subheader("Judge's criterion decisions")
            score_df = pd.DataFrame(scores)
            st.dataframe(score_df, use_container_width=True, hide_index=True)
            st.subheader("Submit an independent expert label")
            component_options = {
                f"{row.get('component_id')} · {row.get('criterion_name', 'Criterion')}": row
                for row in scores
            }
            selected_label = st.selectbox("Criterion to review", list(component_options))
            criterion = component_options[selected_label]
            with st.container(border=True):
                st.caption(f"{criterion.get('parent_category', 'Category')} · {criterion.get('component_id', '')}")
                st.markdown(f"**Evaluation question**\n\n{criterion.get('evaluation_question', '')}")
                if criterion.get("pass_fail_criteria"):
                    st.markdown(f"**Pass/fail criteria**\n\n{criterion['pass_fail_criteria']}")
                with st.expander("View judge rationale and evidence"):
                    st.write(criterion.get("rationale", "No rationale returned by judge."))
                    st.write(criterion.get("evidence", "No evidence returned by judge."))
            with st.form("expert_criterion_annotation"):
                annotator = st.text_input("Expert reviewer ID", placeholder="e.g. expert-01")
                verdict = st.radio("Your independent verdict", ["pass", "fail", "not_applicable"], horizontal=True)
                evidence = st.text_area("Evidence from the assistant response", height=110, placeholder="Quote the response or identify the missing/incorrect behavior.")
                rationale = st.text_area("Reason for your verdict", height=90)
                confidence = st.slider("Confidence", 1, 5, 4)
                submit_human = st.form_submit_button("Submit expert label", type="primary", use_container_width=True)
            if submit_human:
                if not annotator.strip() or len(evidence.strip()) < 3:
                    st.error("Provide a reviewer ID and evidence.")
                else:
                    try:
                        out = api("POST", "/rubrics/human-annotations", json={
                            "evaluation_id": payload["rubric_evaluation_id"],
                            "component_id": criterion["component_id"],
                            "annotator_id": annotator.strip(),
                            "verdict": verdict,
                            "evidence": evidence.strip(),
                            "rationale": rationale.strip(),
                            "confidence": confidence,
                        })
                        st.success(f"Expert label saved · {out.get('human_annotation_id', 'recorded')}")
                    except Exception as exc:
                        st.error(f"Could not save expert label: {exc}")
            st.divider()
            with st.expander("Adjudicate this criterion", expanded=False):
                st.write("Use adjudication when independent reviewers disagree or a final authoritative label is required.")
                with st.form("final_adjudication"):
                    adjudicator = st.text_input("Adjudicator ID", placeholder="e.g. lead-reviewer")
                    final_verdict = st.radio("Final verdict", ["pass", "fail", "not_applicable"], horizontal=True, key="adjudicated_verdict")
                    final_evidence = st.text_area("Evidence supporting the final verdict", height=90)
                    notes = st.text_area("Adjudication notes", height=80)
                    submit_adjudication = st.form_submit_button("Save final adjudication", use_container_width=True)
                if submit_adjudication:
                    if not adjudicator.strip() or len(final_evidence.strip()) < 3:
                        st.error("Provide an adjudicator ID and evidence.")
                    else:
                        try:
                            out = api("POST", "/rubrics/adjudications", json={
                                "evaluation_id": payload["rubric_evaluation_id"],
                                "component_id": criterion["component_id"],
                                "adjudicator_id": adjudicator.strip(),
                                "verdict": final_verdict,
                                "evidence": final_evidence.strip(),
                                "notes": notes.strip(),
                            })
                            st.success(f"Final adjudication saved · {out.get('final_verdict', final_verdict)}")
                        except Exception as exc:
                            st.error(f"Could not save adjudication: {exc}")

with tab_report:
    st.subheader("Compare judge labels with expert references")
    st.write("The report uses final adjudicated labels when available; otherwise it uses an unambiguous human majority. Tied votes are excluded.")
    with st.form("calibration_settings"):
        rubric_id = st.text_input("Rubric ID (optional)", placeholder="Leave blank to include all rubrics")
        col_a, col_b = st.columns(2)
        with col_a:
            min_samples = st.number_input("Minimum samples per criterion", min_value=2, max_value=1000, value=5)
        with col_b:
            agreement = st.slider("Exact-agreement threshold", 0.0, 1.0, 0.80, 0.05)
        save = st.checkbox("Save this calibration run to the database", value=True)
        run = st.form_submit_button("Run calibration report", type="primary", use_container_width=True)
    if run:
        try:
            with st.spinner("Comparing expert reference labels with judge outputs…"):
                report = api("POST", "/rubrics/calibration", json={
                    "rubric_id": rubric_id.strip() or None,
                    "min_samples": int(min_samples),
                    "reliability_threshold": agreement,
                    "save_run": save,
                }, timeout=120)
            st.session_state["calibration_report"] = report
        except Exception as exc:
            st.error(f"Calibration could not run: {exc}")

    report = st.session_state.get("calibration_report")
    if report:
        overall = report.get("overall", {})
        st.divider()
        st.subheader("Overall agreement")
        cols = st.columns(3)
        cols[0].metric("Compared labels", overall.get("sample_count", 0))
        exact = overall.get("exact_agreement")
        cols[1].metric("Exact agreement", f"{exact:.1%}" if isinstance(exact, (int, float)) else "—")
        kappa = overall.get("cohen_kappa")
        cols[2].metric("Cohen's kappa", f"{kappa:.3f}" if isinstance(kappa, (int, float)) else "—")
        st.caption(report.get("method", ""))
        if report.get("calibration_run_id"):
            st.caption(f"Saved calibration run: {report['calibration_run_id']}")
        criteria = pd.DataFrame(report.get("criteria", []))
        if criteria.empty:
            st.info("No comparable expert/adjudicated labels yet. Annotate rubric evaluations first.")
        else:
            st.subheader("Criterion-level reliability")
            st.dataframe(criteria, use_container_width=True, hide_index=True)
            if "reliability_status" in criteria.columns:
                flagged = criteria[criteria["reliability_status"] != "reliable"]
                st.subheader("Criteria needing attention")
                if flagged.empty:
                    st.success("No criteria crossed the configured reliability thresholds.")
                else:
                    st.warning(f"{len(flagged)} criteria need more labels or further review.")
                    st.dataframe(flagged, use_container_width=True, hide_index=True)
